import { ASSET_BUSINESS_STATE } from "./constants.js";
import { DomainError } from "./types.js";

const ALLOWED_ASSET_TRANSITIONS: Record<string, string[]> = {
	[ASSET_BUSINESS_STATE.DRAFT_ASSET]: [ASSET_BUSINESS_STATE.LISTED, ASSET_BUSINESS_STATE.ARCHIVED],
	[ASSET_BUSINESS_STATE.LISTED]: [
		ASSET_BUSINESS_STATE.INTEREST_RECEIVED,
		ASSET_BUSINESS_STATE.NEGOTIATING,
		ASSET_BUSINESS_STATE.DRAFT_ASSET,
		ASSET_BUSINESS_STATE.ARCHIVED,
	],
	[ASSET_BUSINESS_STATE.INTEREST_RECEIVED]: [
		ASSET_BUSINESS_STATE.NEGOTIATING,
		ASSET_BUSINESS_STATE.BOOKED,
		ASSET_BUSINESS_STATE.DRAFT_ASSET,
	],
	[ASSET_BUSINESS_STATE.NEGOTIATING]: [
		ASSET_BUSINESS_STATE.BOOKED,
		ASSET_BUSINESS_STATE.LISTED,
		ASSET_BUSINESS_STATE.DRAFT_ASSET,
	],
	[ASSET_BUSINESS_STATE.BOOKED]: [
		ASSET_BUSINESS_STATE.RENTED,
		ASSET_BUSINESS_STATE.NEGOTIATING,
		ASSET_BUSINESS_STATE.MAINTENANCE,
	],
	[ASSET_BUSINESS_STATE.RENTED]: [
		ASSET_BUSINESS_STATE.RETURN_PENDING,
		ASSET_BUSINESS_STATE.MAINTENANCE,
	],
	[ASSET_BUSINESS_STATE.RETURN_PENDING]: [
		ASSET_BUSINESS_STATE.MAINTENANCE,
		ASSET_BUSINESS_STATE.RENTED,
	],
	[ASSET_BUSINESS_STATE.MAINTENANCE]: [
		ASSET_BUSINESS_STATE.DRAFT_ASSET,
		ASSET_BUSINESS_STATE.LISTED,
		ASSET_BUSINESS_STATE.ARCHIVED,
	],
	[ASSET_BUSINESS_STATE.ARCHIVED]: [],
};

export function assertAllowedAssetTransition(from: string, to: string, command: string): void {
	if (from === to) return;
	const allowed = ALLOWED_ASSET_TRANSITIONS[from] ?? [];
	if (!allowed.includes(to)) {
		throw new DomainError(
			"INVALID_ASSET_TRANSITION",
			`${command} cannot move asset from ${from} to ${to}`,
			409,
		);
	}
}
